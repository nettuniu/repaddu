#include "repaddu/cli_parse.h"
#include "repaddu/cli_run.h"
#include "repaddu/core_types.h"
#include "repaddu/json_lite.h"

#include <cassert>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>

namespace
    {
    std::string readText(const std::filesystem::path& path)
        {
        std::ifstream input(path);
        return std::string((std::istreambuf_iterator<char>(input)), std::istreambuf_iterator<char>());
        }

    void setupFixtureRepo(const std::filesystem::path& root)
        {
        std::error_code ec;
        std::filesystem::create_directories(root / "src", ec);
        std::filesystem::create_directories(root / "vendor" / "dep", ec);

        {
            std::ofstream f(root / "src" / "main.cpp");
            f << "#include <iostream>\nint main() { return 0; }\n";
        }
        {
            std::ofstream f(root / "src" / "generated.cpp");
            f << "// Code generated by protoc. DO NOT EDIT.\nint gen() { return 1; }\n";
        }
        {
            std::ofstream f(root / "vendor" / "dep" / "third_party.cpp");
            f << "int thirdParty() { return 99; }\n";
        }
        }

    void test_default_behavior_keeps_files()
        {
        const std::filesystem::path tempDir = std::filesystem::temp_directory_path() / "repaddu_test_noise_fixture";
        const std::filesystem::path outDir = std::filesystem::temp_directory_path() / "repaddu_test_noise_default_out";
        std::error_code ec;
        std::filesystem::remove_all(tempDir, ec);
        std::filesystem::remove_all(outDir, ec);

        setupFixtureRepo(tempDir);

        repaddu::core::CliOptions options;
        options.inputPath = tempDir;
        options.outputPath = outDir;

        const auto res = repaddu::cli::run(options, nullptr);
        assert(res.code == repaddu::core::ExitCode::success);

        // Under default behavior, vendor and generated files are NOT excluded
        const std::string manifestText = readText(outDir / "manifest.json");
        repaddu::json::JsonValue root;
        assert(repaddu::json::parse(manifestText, root).code == repaddu::core::ExitCode::success);
        assert(root.getObject().at("stats").getObject().at("total_files").getNumber() == 3.0);

        std::filesystem::remove_all(tempDir, ec);
        std::filesystem::remove_all(outDir, ec);
        }

    void test_exclude_vendor_and_generated()
        {
        const std::filesystem::path tempDir = std::filesystem::temp_directory_path() / "repaddu_test_noise_fixture2";
        const std::filesystem::path outDir = std::filesystem::temp_directory_path() / "repaddu_test_noise_filtered_out";
        std::error_code ec;
        std::filesystem::remove_all(tempDir, ec);
        std::filesystem::remove_all(outDir, ec);

        setupFixtureRepo(tempDir);

        repaddu::core::CliOptions options;
        options.inputPath = tempDir;
        options.outputPath = outDir;
        options.excludeVendor = true;
        options.excludeGenerated = true;

        const auto res = repaddu::cli::run(options, nullptr);
        assert(res.code == repaddu::core::ExitCode::success);

        // Only src/main.cpp remains
        const std::string manifestText = readText(outDir / "manifest.json");
        repaddu::json::JsonValue root;
        assert(repaddu::json::parse(manifestText, root).code == repaddu::core::ExitCode::success);
        assert(root.getObject().at("stats").getObject().at("total_files").getNumber() == 1.0);

        // Check exclusions object in manifest
        const auto& exclusionsObj = root.getObject().at("exclusions").getObject();
        assert(exclusionsObj.at("total_excluded").getNumber() == 2.0);
        const auto& byReason = exclusionsObj.at("by_reason").getObject();
        assert(byReason.at("vendor").getNumber() == 1.0);
        assert(byReason.at("generated").getNumber() == 1.0);

        // Check overview has Exclusion summary
        const std::string overviewText = readText(outDir / "000_overview.md");
        assert(overviewText.find("## Exclusion summary") != std::string::npos);
        assert(overviewText.find("1 vendor") != std::string::npos);
        assert(overviewText.find("1 generated") != std::string::npos);

        std::filesystem::remove_all(tempDir, ec);
        std::filesystem::remove_all(outDir, ec);
        }

    void test_cli_parsing_exclusion_flags()
        {
        const std::vector<std::string> args = {
            "repaddu", "-i", ".", "-o", "out",
            "--exclude-vendor",
            "--exclude-generated",
            "--exclusion-report"
        };
        const auto parsed = repaddu::cli::parseArgs(args);
        assert(parsed.result.code == repaddu::core::ExitCode::success);
        assert(parsed.options.excludeVendor == true);
        assert(parsed.options.excludeGenerated == true);
        assert(parsed.options.emitExclusionReport == true);
        }
    }

int main()
    {
    test_default_behavior_keeps_files();
    test_exclude_vendor_and_generated();
    test_cli_parsing_exclusion_flags();
    std::cout << "All exclusion and noise E2E tests passed successfully.\n";
    return 0;
    }
