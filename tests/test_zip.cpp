namespace
    {
    void test_direct_zip_write_and_verify()
        {
        const std::filesystem::path zipPath = std::filesystem::temp_directory_path() / "repaddu_test_direct.zip";
        std::error_code ec;
        std::filesystem::remove(zipPath, ec);

        std::vector<repaddu::io::ZipEntry> entries;
        const std::string textContent = "Hello World! This is a test file for repaddu ZIP archive creation. "
                                        "Testing repetition for compression: ABCDEFGHIJKLMNOPQRSTUVWXYZ 1234567890.\n";
        entries.push_back({ "000_overview.md", std::vector<std::uint8_t>(textContent.begin(), textContent.end()) });
        entries.push_back({ "empty.txt", {} });
        entries.push_back({ "sub/nested.md", std::vector<std::uint8_t>(textContent.begin(), textContent.end()) });

        const repaddu::core::RunResult writeRes = repaddu::io::writeZipArchive(zipPath, entries);
        assert(writeRes.code == repaddu::core::ExitCode::success);
        assert(std::filesystem::exists(zipPath));
        assert(std::filesystem::file_size(zipPath) > 0);

        // Verify headers by reading binary
        std::ifstream ifs(zipPath, std::ios::binary);
        assert(ifs.is_open());
        std::vector<char> buffer((std::istreambuf_iterator<char>(ifs)), std::istreambuf_iterator<char>());
        assert(buffer.size() >= 22);

        // Check local file header signature
        assert(static_cast<unsigned char>(buffer[0]) == 0x50);
        assert(static_cast<unsigned char>(buffer[1]) == 0x4b);
        assert(static_cast<unsigned char>(buffer[2]) == 0x03);
        assert(static_cast<unsigned char>(buffer[3]) == 0x04);

        // Check EOCD signature in last 22 bytes
        const std::size_t eocdOffset = buffer.size() - 22;
        assert(static_cast<unsigned char>(buffer[eocdOffset]) == 0x50);
        assert(static_cast<unsigned char>(buffer[eocdOffset + 1]) == 0x4b);
        assert(static_cast<unsigned char>(buffer[eocdOffset + 2]) == 0x05);
        assert(static_cast<unsigned char>(buffer[eocdOffset + 3]) == 0x06);

        std::filesystem::remove(zipPath, ec);
        }

    void test_create_zip_from_directory()
        {
        const std::filesystem::path tempDir = std::filesystem::temp_directory_path() / "repaddu_test_zip_dir";
        const std::filesystem::path zipPath = std::filesystem::temp_directory_path() / "repaddu_test_from_dir.zip";
        std::error_code ec;
        std::filesystem::remove_all(tempDir, ec);
        std::filesystem::remove(zipPath, ec);

        std::filesystem::create_directories(tempDir / "subdir", ec);
        {
            std::ofstream f1(tempDir / "000_overview.md");
            f1 << "# Overview\nGenerated by repaddu.\n";
            std::ofstream f2(tempDir / "001_tree.md");
            f2 << "# Tree\n- src/main.cpp\n";
            std::ofstream f3(tempDir / "subdir/nested.md");
            f3 << "# Nested\nSubdir content\n";
        }

        const repaddu::core::RunResult res = repaddu::io::createZipFromDirectory(tempDir, zipPath);
        assert(res.code == repaddu::core::ExitCode::success);
        assert(std::filesystem::exists(zipPath));
        assert(std::filesystem::file_size(zipPath) > 0);

        std::filesystem::remove_all(tempDir, ec);
        std::filesystem::remove(zipPath, ec);
        }

    void test_cli_parsing_zip_flags()
        {
        {
            const std::vector<std::string> args = { "repaddu", "-i", ".", "-o", "out", "-z" };
            const auto parsed = repaddu::cli::parseArgs(args);
            assert(parsed.result.code == repaddu::core::ExitCode::success);
            assert(parsed.options.zipOutput == true);
            assert(parsed.options.outputPath == "out");
        }
        {
            const std::vector<std::string> args = { "repaddu", "-i", ".", "-o", "out", "--zip" };
            const auto parsed = repaddu::cli::parseArgs(args);
            assert(parsed.result.code == repaddu::core::ExitCode::success);
            assert(parsed.options.zipOutput == true);
        }
        {
            const std::vector<std::string> args = { "repaddu", "-i", ".", "-o", "out", "--zip-path", "my_custom.zip" };
            const auto parsed = repaddu::cli::parseArgs(args);
            assert(parsed.result.code == repaddu::core::ExitCode::success);
            assert(parsed.options.zipOutput == true);
            assert(parsed.options.zipPath == "my_custom.zip");
        }
        {
            const std::vector<std::string> args = { "repaddu", "-i", ".", "-o", "archive.zip" };
            const auto parsed = repaddu::cli::parseArgs(args);
            assert(parsed.result.code == repaddu::core::ExitCode::success);
            assert(parsed.options.zipOutput == true);
            assert(parsed.options.zipPath == "archive.zip");
            assert(parsed.options.outputPath == "archive");
        }
        }

    void test_end_to_end_app_run_with_zip()
        {
        const std::filesystem::path outDir = std::filesystem::temp_directory_path() / "repaddu_e2e_zip_out";
        const std::filesystem::path zipPath = std::filesystem::temp_directory_path() / "repaddu_e2e_zip_out.zip";
        std::error_code ec;
        std::filesystem::remove_all(outDir, ec);
        std::filesystem::remove(zipPath, ec);

        repaddu::core::CliOptions options;
        options.inputPath = std::filesystem::path(REPADDU_TEST_ROOT) / "fixtures/sample_repo";
        options.outputPath = outDir;
        options.zipOutput = true;

        const repaddu::core::RunResult result = repaddu::cli::run(options, nullptr);
        assert(result.code == repaddu::core::ExitCode::success);

        assert(std::filesystem::exists(outDir));
        assert(std::filesystem::exists(zipPath));
        assert(std::filesystem::file_size(zipPath) > 0);

        std::filesystem::remove_all(outDir, ec);
        std::filesystem::remove(zipPath, ec);
        }

    void test_dry_run_does_not_create_zip()
        {
        const std::filesystem::path outDir = std::filesystem::temp_directory_path() / "repaddu_dry_zip_out";
        const std::filesystem::path zipPath = std::filesystem::temp_directory_path() / "repaddu_dry_zip_out.zip";
        std::error_code ec;
        std::filesystem::remove_all(outDir, ec);
        std::filesystem::remove(zipPath, ec);

        repaddu::core::CliOptions options;
        options.inputPath = std::filesystem::path(REPADDU_TEST_ROOT) / "fixtures/sample_repo";
        options.outputPath = outDir;
        options.zipOutput = true;
        options.dryRun = true;

        const repaddu::core::RunResult result = repaddu::cli::run(options, nullptr);
        assert(result.code == repaddu::core::ExitCode::success);

        assert(!std::filesystem::exists(zipPath));

        std::filesystem::remove_all(outDir, ec);
        std::filesystem::remove(zipPath, ec);
        }
    }

int main()
    {
    test_direct_zip_write_and_verify();
    test_create_zip_from_directory();
    test_cli_parsing_zip_flags();
    test_end_to_end_app_run_with_zip();
    test_dry_run_does_not_create_zip();
    std::cout << "All ZIP tests passed successfully.\n";
    return 0;
    }
