#include "repaddu/noise_detector.h"

#include <cassert>
#include <filesystem>
#include <fstream>
#include <iostream>

namespace
    {
    void test_is_vendor_path()
        {
        assert(repaddu::noise::isVendorPath("vendor/lib.cpp"));
        assert(repaddu::noise::isVendorPath("third_party/zlib/inflate.c"));
        assert(repaddu::noise::isVendorPath("node_modules/lodash/index.js"));
        assert(repaddu::noise::isVendorPath("submodules/gtest/src/gtest.cc"));
        assert(repaddu::noise::isVendorPath("extern/fmt/format.cc"));
        assert(!repaddu::noise::isVendorPath("src/vendor_manager.cpp"));
        assert(!repaddu::noise::isVendorPath("src/main.cpp"));
        }

    void test_is_noise_path()
        {
        assert(repaddu::noise::isNoisePath("build/Makefile"));
        assert(repaddu::noise::isNoisePath("dist/bundle.js"));
        assert(repaddu::noise::isNoisePath(".cache/clangd/index.idx"));
        assert(repaddu::noise::isNoisePath("__pycache__/module.cpython-310.pyc"));
        assert(!repaddu::noise::isNoisePath("src/builder.cpp"));
        }

    void test_is_lock_file()
        {
        assert(repaddu::noise::isLockFile("package-lock.json"));
        assert(repaddu::noise::isLockFile("Cargo.lock"));
        assert(repaddu::noise::isLockFile("poetry.lock"));
        assert(repaddu::noise::isLockFile("yarn.lock"));
        assert(!repaddu::noise::isLockFile("CMakeLists.txt"));
        assert(!repaddu::noise::isLockFile("main.cpp"));
        }

    void test_is_minified_file()
        {
        assert(repaddu::noise::isMinifiedFile("app.min.js"));
        assert(repaddu::noise::isMinifiedFile("styles.min.css"));
        assert(!repaddu::noise::isMinifiedFile("app.js"));
        assert(!repaddu::noise::isMinifiedFile("styles.css"));
        }

    void test_is_generated_sample_and_file()
        {
        assert(repaddu::noise::isGeneratedSample("// Code generated by protoc. DO NOT EDIT.\npackage main"));
        assert(repaddu::noise::isGeneratedSample("/* @generated by tool */\nint x = 0;"));
        assert(repaddu::noise::isGeneratedSample("// This file is automatically generated by moc"));
        assert(!repaddu::noise::isGeneratedSample("// Copyright 2026 Author\nint main() { return 0; }"));

        const std::filesystem::path tempFile = std::filesystem::temp_directory_path() / "repaddu_test_gen.cpp";
        {
            std::ofstream out(tempFile, std::ios::binary);
            out << "// Automatically generated by generator. DO NOT EDIT.\nint foo() { return 42; }\n";
        }

        assert(repaddu::noise::isGeneratedCode(tempFile));

        std::error_code ec;
        std::filesystem::remove(tempFile, ec);
        }

    void test_exclusion_report()
        {
        repaddu::noise::ExclusionReport report;
        report.record("vendor/foo.c", repaddu::noise::ExclusionReason::vendor, 1024, "vendor directory");
        report.record("gen/proto.pb.cc", repaddu::noise::ExclusionReason::generated, 2048, "do not edit banner");
        report.record("bin/image.png", repaddu::noise::ExclusionReason::binary, 512, "binary");

        assert(report.totalExcluded() == 3);
        assert(report.countVendor == 1);
        assert(report.countGenerated == 1);
        assert(report.countBinary == 1);

        const std::string text = repaddu::noise::renderExclusionSummaryText(report);
        assert(text.find("Excluded 3 files") != std::string::npos);
        assert(text.find("1 vendor") != std::string::npos);
        assert(text.find("1 generated") != std::string::npos);
        assert(text.find("1 binaries") != std::string::npos);
        }
    }

int main()
    {
    test_is_vendor_path();
    test_is_noise_path();
    test_is_lock_file();
    test_is_minified_file();
    test_is_generated_sample_and_file();
    test_exclusion_report();
    std::cout << "Noise detector unit tests passed successfully.\n";
    return 0;
    }
